def paint_face(body):
    """Black and split down the middle like cracked bark, with pale lips and no visible eyes (arboretum.md 4).
    Paints the front of the skull in the albedo; the split's lips are pale sapwood."""
    material = body.data.materials[0]
    tex = next(n for n in material.node_tree.nodes if n.type == "TEX_IMAGE")
    image = tex.image
    image.scale(TEXTURE, TEXTURE)
    w = h = TEXTURE
    pixels = array("f", [0.]) * (w * h * 4)
    image.pixels.foreach_get(pixels)
    mesh = body.data
    uv = mesh.uv_layers.active.data
    head = body.vertex_groups["Head"].index
    mid = -.015
    mesh.calc_loop_triangles()
    painted = 0

    def head_weight(vi):
        return sum(g.weight for g in mesh.vertices[vi].groups if g.group == head)

    for tri in mesh.loop_triangles:
        pts = [mesh.vertices[i].co.copy() for i in tri.vertices]
        centre = sum(pts, Vector()) / 3
        if not (centre.y < -.13 and 1.94 < centre.z < 2.36 and abs(centre.x - mid) < .15):
            continue
        if min(head_weight(i) for i in tri.vertices) < .5:
            continue
        uvs = [Vector((uv[li].uv.x * w, uv[li].uv.y * h)) for li in tri.loops]
        (ax, ay), (bx, by), (cx, cy) = uvs
        det = (by - cy) * (ax - cx) + (cx - bx) * (ay - cy)
        if abs(det) < 1e-9:
            continue
        longest = max((uvs[0] - uvs[1]).length, (uvs[1] - uvs[2]).length, (uvs[2] - uvs[0]).length)
        slack = 1.5 * longest / abs(det)  # about a texel and a half past each edge, against seams
        for py in range(int(min(ay, by, cy)) - 2, int(max(ay, by, cy)) + 3):
            for px in range(int(min(ax, bx, cx)) - 2, int(max(ax, bx, cx)) + 3):
                if not (0 <= px < w and 0 <= py < h):
                    continue
                sx, sy = px + .5, py + .5
                l1 = ((by - cy) * (sx - cx) + (cx - bx) * (sy - cy)) / det
                l2 = ((cy - ay) * (sx - cx) + (ax - cx) * (sy - cy)) / det
                l3 = 1 - l1 - l2
                if min(l1, l2, l3) < -slack:
                    continue
                p = pts[0] * l1 + pts[1] * l2 + pts[2] * l3
                fade = (smoothstep((-.135 - p.y) / .04) * smoothstep((p.z - 1.95) / .03) *
                        smoothstep((2.35 - p.z) / .04) * smoothstep((.14 - abs(p.x - mid)) / .03))
                if fade <= 0:
                    continue
                # Bark: charcoal with a vertical grain.
                grain = .5 + .5 * sin(p.x * 410 + sin(p.z * 37) * 2.3) * sin(p.z * 23 + p.x * 90)
                # Lifted from pure black so the mask still reads as wood under a torch at 480x270.
                colour = [.11 + .06 * grain, .092 + .048 * grain, .075 + .036 * grain]
                # The split runs from the brow to the chin and wanders a little.
                if 1.97 < p.z < 2.25:
                    centre_x = mid + .006 * sin(p.z * 61)
                    off = abs(p.x - centre_x)
                    taper = smoothstep((p.z - 1.97) / .04) * smoothstep((2.25 - p.z) / .05)
                    gap, lip = .007 * taper, .022 * taper
                    if off < gap:
                        colour = [.004, .003, .003]
                    elif off < lip:
                        pale = 1 - (off - gap) / max(lip - gap, 1e-6) * .45
                        colour = [.86 * pale, .8 * pale, .66 * pale]
                k = (py * w + px) * 4
                for c in range(3):
                    pixels[k + c] = pixels[k + c] * (1 - fade) + colour[c] * fade
                painted += 1
    image.pixels.foreach_set(pixels)
    image.update()
    image.pack()
    return painted


