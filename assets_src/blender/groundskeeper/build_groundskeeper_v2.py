def render(rig, directory):
    directory.mkdir(parents=True, exist_ok=True)
    scene = bpy.context.scene
    for track in rig.animation_data.nla_tracks:
        track.mute = True
    rig.animation_data.use_nla = False
    scene.render.engine = "BLENDER_WORKBENCH"
    scene.display.shading.light = "STUDIO"
    scene.display.shading.color_type = "SINGLE"
    scene.display.shading.single_color = (.55, .55, .55)
    scene.render.resolution_x, scene.render.resolution_y = 720, 960
    scene.render.image_settings.file_format = "PNG"
    camera = bpy.data.objects.new("Camera", bpy.data.cameras.new("Camera"))
    scene.collection.objects.link(camera)
    scene.camera = camera
    camera.data.type = "ORTHO"
    camera.data.ortho_scale = 3.3
    scene.world = bpy.data.worlds.new("Mid grey")
    scene.world.color = (.18, .18, .18)
    scene.render.film_transparent = False

    def pose_at(clip, time):
        rig.animation_data.action = bpy.data.actions[clip]
        rig.animation_data.action_slot = rig.animation_data.action.slots[0]
        frame = time * FPS
        scene.frame_set(int(frame), subframe=frame % 1)

    def shoot(location, target, name):
        camera.location = location
        camera.rotation_euler = (Vector(target) - camera.location).to_track_quat("-Z", "Y").to_euler()
        scene.render.filepath = str(directory / name)
        bpy.ops.render.render(write_still=True)

    shots = {"rest": ("listen", 0.), "lean-hold": ("lean", LEAN_HOLD + .2), "snatch": ("snatch", 4 / FPS),
             "hearing": ("tilt", .3), "walk": ("walk", .1)}
    for label, (clip, time) in shots.items():
        pose_at(clip, time)
        for view, location in (("front", (0, -8, 1.55)), ("side", (8, 0, 1.55))):
            shoot(location, (0, 0, 1.55), f"groundskeeper-{label}-{view}.png")
    # The real colours, plainly lit on mid grey.
    scene.display.shading.color_type = "TEXTURE"
    for label, view in (("walk", "front"), ("snatch", "side"), ("lean-hold", "front"), ("rest", "front")):
        pose_at(*shots[label])
        shoot((0, -8, 1.55) if view == "front" else (8, 0, 1.55), (0, 0, 1.55),
              f"groundskeeper-textured-{label}-{view}.png")
    pose_at("listen", 0.)
    camera.data.ortho_scale = .9
    shoot((0, -8, 2.35), (0, 0, 2.35), "groundskeeper-face-textured.png")
    # The game's own frame: 480x270, a torch from the camera 3.5 m away, the greenhouse dark.
    scene.render.engine = "BLENDER_EEVEE"
    scene.render.resolution_x, scene.render.resolution_y = 480, 270
    scene.world.color = (.012, .014, .016)
    scene.view_settings.view_transform = "AgX"
    camera.data.type = "PERSP"
    camera.data.lens = 22
    torch = bpy.data.objects.new("Torch", bpy.data.lights.new("Torch", "SPOT"))
    scene.collection.objects.link(torch)
    torch.data.energy, torch.data.spot_size, torch.data.spot_blend = 160, .7, .5
    torch.data.color = (1, .88, .7)
    for label, distance in (("rest", 3.5), ("lean-hold", 3.5), ("rest", 6.)):
        pose_at(*shots[label])
        eye = Vector((.3, -distance, 1.6))
        torch.location = eye + Vector((.15, 0, -.1))
        torch.rotation_euler = (Vector((0, 0, 1.9)) - torch.location).to_track_quat("-Z", "Y").to_euler()
        shoot(eye, (0, 0, 1.75), f"groundskeeper-game-{label}-{distance:.1f}m.png")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--mixamo-dir", type=Path, required=True, help="directory with the six motion FBXs")
    parser.add_argument("--render", type=Path, help="write grey studies here")
    args = parser.parse_args(sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else [])
    bpy.ops.wm.read_factory_settings(use_empty=True)
    shears = old_shears()
    rig, body = import_meshy()
    rename_bones(rig, body)
    print(f"removed the shoulder branch: {remove_shoulder_branch(body)} vertices")
    print("small pieces: %d vertices of floating islands removed, %d pieces made rigid" % rigid_parts(body))
    print(f"tags and beard re-skinned: {hanging_parts(body)} vertices")
    print(f"face repainted: {paint_face(body)} texels")
    to_game = game_space(rig)
    scale_and_centre(rig, body, to_game)
    blade_axis = add_props(rig, body, shears, to_game)
    for bone in rig.data.bones:
        print(f"bone {bone.name:10s} parent {bone.parent.name if bone.parent else '-':9s} head {tuple(round(c, 3) for c in bone.head_local)}")
