def import_meshy():
    bpy.ops.import_scene.gltf(filepath=str(SOURCE))
    for obj in list(bpy.context.scene.objects):
        if obj.type not in ("ARMATURE", "MESH") or obj.name.startswith("Icosphere"):
            bpy.data.objects.remove(obj, do_unlink=True)   # Meshy leaves a stray unit sphere in the file
    rig, = [o for o in bpy.context.scene.objects if o.type == "ARMATURE"]
    body, = [o for o in bpy.context.scene.objects if o.type == "MESH"]
    rig.name = rig.data.name = "GroundskeeperRig"
    body.name = body.data.name = "Groundskeeper"
    return rig, body


def game_space(rig):
    """Meshy units -> today's figure: Head joint at 2.29 m, feet on 0 (Meshy's already are), hips over the
    origin, facing -Y as today's (Godot +Z). Meshy already faces -Y and stands in an A-pose."""
    hips = rig.data.bones["Hips"].head_local
    return Matrix.Scale(SCALE, 4) @ Matrix.Translation((-hips.x, -hips.y, 0))


def scale_and_centre(rig, body, to_game):
    body.parent = None
    for obj in (rig, body):
        obj.matrix_world = to_game
    bpy.ops.object.select_all(action="DESELECT")
    for obj in (rig, body):
        obj.select_set(True)
    bpy.context.view_layer.objects.active = rig
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    body.parent = rig
    assert abs(min(v.co.z for v in body.data.vertices)) < .005, "feet should stand on the floor"


def remove_shoulder_branch(body):
    """ONE branch. Meshy grew a second, smaller three-tined branch out of the top of the left shoulder.
    In Meshy's units it is everything left of x 0.13 between 1.92 m and 2.2 m, clear of the back."""
    bm = bmesh.new()
    bm.from_mesh(body.data)
    doomed = [v for v in bm.verts if v.co.x > .13 and 1.92 < v.co.z < 2.2 and -.15 < v.co.y < .08]
    count = len(doomed)
    bmesh.ops.delete(bm, geom=doomed, context="VERTS")
    bm.to_mesh(body.data)
    bm.free()
    return count


def rename_bones(rig, body):
    groups = body.vertex_groups
    for old, into in FOLD.items():
        source = groups.get("mixamorig:" + old) or groups.get(old)
        if source is None:
            continue
        target_name = "mixamorig:" + next(k for k, v in RENAME.items() if v == into)
        target = groups[target_name]
        for v in body.data.vertices:
            for g in v.groups:
                if g.group == source.index and g.weight > 0:
                    target.add([v.index], g.weight, "ADD")
        groups.remove(source)
    bpy.context.view_layer.objects.active = rig
    bpy.ops.object.mode_set(mode="EDIT")
    bones = rig.data.edit_bones
    for old in FOLD:
        bone = bones.get("mixamorig:" + old) or bones.get(old)
        if bone is not None:
            bones.remove(bone)
    root = bones.new("Root")
    hips = bones["mixamorig:Hips"].head
    root.head, root.tail = (hips.x, hips.y, 0), (hips.x, hips.y, .21)   # lands on the origin in game space
    bones["mixamorig:Hips"].parent = root
    bpy.ops.object.mode_set(mode="OBJECT")
    for old, new in RENAME.items():
        rig.data.bones["mixamorig:" + old].name = new
        group = groups.get("mixamorig:" + old)
        if group is not None:
            group.name = new


def rigid_parts(body):
    """Meshy's loose bits (lichen, flakes, splinters) are skinned across several bones and stretch when the
    body bends. Weld by position to find the real pieces: tiny floating islands go, every other small piece
    rides rigidly with its strongest bone. The dead branch above the skull rides the Head and the root
    growth behind the back rides the Chest, so neither stretches between two bones."""
    mesh = body.data
    names = {g.index: g.name for g in body.vertex_groups}
    key = [tuple(round(c * 2000) for c in v.co) for v in mesh.vertices]
    parent = {k: k for k in key}

    def find(k):
        while parent[k] != k:
            parent[k] = parent[parent[k]]
            k = parent[k]
        return k

    for edge in mesh.edges:
        a, b = find(key[edge.vertices[0]]), find(key[edge.vertices[1]])
        if a != b:
            parent[a] = b
    pieces = {}
    for v in mesh.vertices:
        pieces.setdefault(find(key[v.index]), []).append(v.index)
    biggest = max(len(p) for p in pieces.values())
    doomed, rigid = [], 0

    def pin(indices, bone):
        for i in indices:
            for g in list(mesh.vertices[i].groups):
                body.vertex_groups[g.group].remove([i])
            body.vertex_groups[bone].add([i], 1., "REPLACE")

    for piece in pieces.values():
        unique = len({key[i] for i in piece})
        if len(piece) == biggest:
            continue
        if unique < 12:
            doomed.extend(piece)
            continue
        share = {}
        for i in piece:
            for g in mesh.vertices[i].groups:
                share[names[g.group]] = share.get(names[g.group], 0) + g.weight
        pin(piece, max(sorted(share), key=share.get))
        rigid += 1
    # The branch above the skull, and its base where it leaves the left of the head.
    pin([v.index for v in mesh.vertices if v.co.z > 2.34 or (v.co.z > 2.2 and v.co.x > .09 and v.co.y > -.2)], "Head")
    # The root growth behind the back.
    pin([v.index for v in mesh.vertices if v.co.y > .16 and 1.42 < v.co.z < 2.1], "Chest")
    bm = bmesh.new()
    bm.from_mesh(mesh)
    bm.verts.ensure_lookup_table()
    bmesh.ops.delete(bm, geom=[bm.verts[i] for i in doomed], context="VERTS")
    bm.to_mesh(mesh)
    bm.free()
    return len(doomed), rigid


def hanging_parts(body):
    """The lichen beard and the dog tags hang in front of the chest. Meshy skinned them to the chest and
    head in patches, so they would tear when he turns his head. Tags go rigidly on Badges, the beard
    rigidly on the Head it hangs from."""
    groups = body.vertex_groups
    badges = groups.new(name="Badges")
    moved = 0
    for v in body.data.vertices:
        x, y, z = v.co
        if abs(x + .02) < .11 and 1.5 < z < 1.99 and y < -.215:
            for g in list(v.groups):
                groups[g.group].remove([v.index])
            # Each piece rides one bone: the tags their own, the beard the chin.
            (badges if z < 1.75 else groups["Head"]).add([v.index], 1., "REPLACE")
            moved += 1
    return moved


