const BLANK = GLYPHS[' ']!;

/** Draws `text` with its top-left at (x, y), one font pixel = `px` canvas pixels. */
export function drawText(g: CanvasRenderingContext2D, text: string, x: number, y: number, px = 1): void {
  for (let i = 0; i < text.length; i++) {
    const rows = GLYPHS[text[i] ?? ' '] ?? BLANK;
    for (let r = 0; r < 7; r++) {
      const row = rows[r] ?? '';
      for (let c = 0; c < 5; c++) if (row[c] === '1') g.fillRect(x + (i * 6 + c) * px, y + r * px, px, px);
    }
  }
}

/** Width in font pixels of a line of text (6 per character, no trailing gap). */
export function textWidth(text: string): number {
  return Math.max(0, text.length * 6 - 1);
}
