def read_take(path, rig, count, first, last, name):
    """Sample a Mixamo take into per-frame world rotation deltas (and the hips' offset) by bone name."""
    scene = bpy.context.scene
    before_objects = set(bpy.data.objects)
    before_actions = set(bpy.data.actions)
    bpy.ops.import_scene.fbx(filepath=str(path))
    imported = set(bpy.data.objects) - before_objects
    source, = [obj for obj in imported if obj.type == "ARMATURE"]
    bones = {bone.name.split(":")[-1]: bone for bone in source.pose.bones}
    missing = [m for m in RENAME if m not in bones]
    if missing:
        raise ValueError(f"{path.name}: the take lacks {missing}")
    axis = source.matrix_world.to_quaternion()
    rest = {m: axis @ bones[m].bone.matrix_local.to_quaternion() for m in RENAME}
    hips_rest = source.matrix_world @ bones["Hips"].bone.head_local
    hips_height = hips_rest.z
    start, end = source.animation_data.action.frame_range
    samples = []
    for index in range(count):
        phase = index / (count - 1)
        if name == "snatch":
            # The bite reaches forward at about 30% of the take. Land that on frame 6, when the blades close.
            impact = 6 / (count - 1)
            fraction = (first + (.30 - first) * phase / impact if phase <= impact else
                        .30 + (last - .30) * (phase - impact) / (1. - impact))
        elif name == "lean":
            fraction = first + (last - first) * min(1., index / FPS / LEAN_HOLD)
        else:
            fraction = first + (last - first) * phase
        if name in ("listen", "walk") and index == count - 1:
            fraction = first   # the loop seam: the last frame is the first
        frame = start + (end - start) * fraction
        scene.frame_set(floor(frame), subframe=frame % 1)
        delta = {RENAME[m]: (axis @ bones[m].matrix.to_quaternion()) @ rest[m].inverted() for m in RENAME}
        hips = source.matrix_world @ bones["Hips"].head - hips_rest
        samples.append((delta, hips / hips_height))
    for obj in imported:
        bpy.data.objects.remove(obj, do_unlink=True)
    for action in set(bpy.data.actions) - before_actions:
        bpy.data.actions.remove(action)
    return samples, {RENAME[m]: rest[m] for m in RENAME}


def reset(rig):
    for bone in rig.pose.bones:
        bone.location = (0, 0, 0)
        bone.rotation_mode = "QUATERNION"
        bone.rotation_quaternion = (1, 0, 0, 0)
        bone.scale = (1, 1, 1)
    bpy.context.view_layer.update()


def apply_sample(rig, sample, source_rest):
    """World-delta retarget. Limbs first turn their A-pose rest onto the take's T-pose rest direction."""
    delta, hips = sample
    world = {}
    for bone in sorted(rig.pose.bones, key=lambda b: len(b.parent_recursive)):
        name = bone.name
        rest = bone.bone.matrix_local.to_quaternion()
        parent_rest = bone.parent.bone.matrix_local.to_quaternion() if bone.parent else Quaternion()
        parent_pose = world.get(bone.parent.name, parent_rest) if bone.parent else Quaternion()
        if name in delta:
            align = (rest @ Y).rotation_difference(source_rest[name] @ Y) if name.startswith(LIMBS) else Quaternion()
            posed = delta[name] @ align @ rest
        else:
            posed = parent_pose @ parent_rest.inverted() @ rest
        world[name] = posed
        bone.rotation_quaternion = (parent_pose @ parent_rest.inverted() @ rest).inverted() @ posed
    pelvis = rig.pose.bones["Hips"]
    height = pelvis.bone.head_local.z
    pelvis.location = pelvis.bone.matrix_local.to_quaternion().inverted() @ (hips * height)
    bpy.context.view_layer.update()


def capture(rig):
    return {b.name: (b.rotation_quaternion.copy(), b.location.copy()) for b in rig.pose.bones}


def restore(rig, pose, other=None, weight=0.):
    for bone in rig.pose.bones:
        q, loc = pose[bone.name]
        if other is not None:
            q2, loc2 = other[bone.name]
            q = q.slerp(q2, weight)
            loc = loc.lerp(loc2, weight)
        bone.rotation_quaternion = q
        bone.location = loc
    bpy.context.view_layer.update()


def aim(bone, direction, weight=1.):
    local = bone.matrix.to_quaternion().inverted() @ direction
    original = bone.rotation_quaternion.copy()
    bone.rotation_quaternion = original.slerp(original @ Y.rotation_difference(local), weight)
    bpy.context.view_layer.update()


def aim_limb(upper, lower, target, bend, weight=1.):
    delta = target - upper.head
    length = min(delta.length, upper.length + lower.length - .001)
    direction = delta.normalized()
    bend = (bend - bend.dot(direction) * direction).normalized()
    along = (upper.length ** 2 + length ** 2 - lower.length ** 2) / (2 * length)
    middle = upper.head + direction * along + bend * sqrt(max(0, upper.length ** 2 - along ** 2))
    aim(upper, middle - upper.head, weight)
    aim(lower, target - lower.head, weight)


def plant_feet(rig):
    """Grounded clips keep both feet where they stand at rest: knees bend, ankles and soles stay put.
    Meshy's legs are nearly straight at rest, so first lower the hips until both ankles are in reach."""
    pelvis = rig.pose.bones["Hips"]
    for _ in range(3):
        excess = 0.
        for side in ("L", "R"):
            thigh, shin, foot = (rig.pose.bones[f"{j}.{side}"] for j in ("Thigh", "Shin", "Foot"))
            reach = (foot.bone.head_local - thigh.head).length
            excess = max(excess, reach - (thigh.length + shin.length - .006))
        if excess <= 0:
            break
        pelvis.location += pelvis.bone.matrix_local.to_quaternion().inverted() @ Vector((0, 0, -excess - .002))
        bpy.context.view_layer.update()
    for side in ("L", "R"):
        thigh, shin, foot, toe = (rig.pose.bones[f"{j}.{side}"] for j in ("Thigh", "Shin", "Foot", "Toe"))
        aim_limb(thigh, shin, foot.bone.head_local.copy(), Vector((0, -1, 0)))
        for part in (foot, toe):
            part.rotation_quaternion = (part.rotation_quaternion @ part.matrix.to_quaternion().inverted()
                                        @ part.bone.matrix_local.to_quaternion())
            bpy.context.view_layer.update()


def ground(rig, rest_low):
    """The walk keeps its stride; lift or drop the hips so the lower foot meets the floor."""
    low = min(rig.pose.bones[f"{j}.{s}"].head.z for j in ("Foot", "Toe") for s in ("L", "R"))
    pelvis = rig.pose.bones["Hips"]
    pelvis.location += pelvis.bone.matrix_local.to_quaternion().inverted() @ Vector((0, 0, rest_low - low))
    bpy.context.view_layer.update()


def grasp_head(rig, weight):
    """The hearing reaction: both wrists at the temples, claws raked back over the skull."""
    head = rig.pose.bones["Head"]
    rest = head.bone.matrix_local.to_quaternion()
    for side, sign in (("L", 1), ("R", -1)):
        upper, fore, hand = (rig.pose.bones[f"{j}.{side}"] for j in ("UpperArm", "Forearm", "Hand"))
        wrist = head.head + head.matrix.to_quaternion() @ (rest.inverted() @ Vector((sign * .22, -.01, .2)))
        aim_limb(upper, fore, wrist, Vector((sign, -.3, -.45)), weight)
        claws = head.matrix.to_quaternion() @ (rest.inverted() @ Vector((sign * .35, .6, .3)))
        aim(hand, claws, weight)


def bend(rig, amount):
    """Today's lean on top of the take: the back folds forward over the hiding place, head down to listen."""
    for name, share in (("Spine", .3), ("Spine1", .35), ("Chest", .35), ("Head", -.25)):
        bone = rig.pose.bones[name]
        axis = bone.bone.matrix_local.to_quaternion().inverted() @ Vector((1, 0, 0))
        bone.rotation_quaternion = Quaternion(axis, amount * share) @ bone.rotation_quaternion
    bpy.context.view_layer.update()


def badges_hang(rig, swing_forward=0., swing_side=0.):
    """The tags hang half by gravity and half along the chest, plus the clip's swing."""
    badges = rig.pose.bones["Badges"]
    chest_down = -(rig.pose.bones["Chest"].matrix.to_quaternion() @ Y)
    down = (Vector((0, 0, -1)) + chest_down).normalized()
    aim(badges, (down + Vector((swing_side, -swing_forward, 0))).normalized())


def blades(rig, axis, opening):
    blade = rig.pose.bones["Blade.B"]
    basis = blade.bone.matrix_local.to_quaternion()
    blade.rotation_quaternion = basis.inverted() @ Quaternion(axis, -2 * opening) @ basis


def animate(rig, mixamo_dir, blade_axis):
    scene = bpy.context.scene
    scene.render.fps = FPS
    rig.animation_data_create()
    rig.animation_data.use_nla = False
    reset(rig)
    rest_low = min(rig.pose.bones[f"{j}.{s}"].head.z for j in ("Foot", "Toe") for s in ("L", "R"))
    takes, source_rest = {}, {}
    for name, (file, first, last) in TAKES.items():
        count = round(CLIPS[name] * FPS) + 1
        takes[name], source_rest[name] = read_take(mixamo_dir / file, rig, count, first, last, name)
        print(f"take {name}: {file} {first:.2f}-{last:.2f}, {count} frames")

    def pose(name, frame):
        reset(rig)
        apply_sample(rig, takes[name][frame], source_rest[name])
        if name == "walk":
            hips = rig.pose.bones["Hips"]
            q = hips.bone.matrix_local.to_quaternion()
            world = q @ hips.location
            hips.location = q.inverted() @ Vector((0, 0, world.z))   # in place: the host moves him
            bpy.context.view_layer.update()
            ground(rig, rest_low)
        else:
            # Feet stay planted, so the hips may shift only a little: the bite lunges a metre and a half and
            # drops into a crouch. Keep within 12 cm sideways and 18 cm down so the claws stay off the floor.
            hips = rig.pose.bones["Hips"]
            q = hips.bone.matrix_local.to_quaternion()
            world = q @ hips.location
            flat = Vector((world.x, world.y))
            if flat.length > .12:
                flat *= .12 / flat.length
            world = Vector((flat.x, flat.y, min(0., max(world.z, -.18))))
            hips.location = q.inverted() @ world
            bpy.context.view_layer.update()
            plant_feet(rig)

    pose("listen", 0)
    badges_hang(rig)
    blades(rig, blade_axis, 0)
    listen0 = capture(rig)
    lean_hold = None
    for name, duration in CLIPS.items():
        stop = round(duration * FPS)
        action = bpy.data.actions.new(name)
        rig.animation_data.action = action
        for frame in range(stop + 1):
            t = frame / FPS
            if name == "recover":
                restore(rig, lean_hold, listen0, smoothstep(t / duration))
            else:
                pose(name, frame)
                if name == "tilt":
                    w = smoothstep(t / .2)
                    restore(rig, listen0, capture(rig), w)
                    plant_feet(rig)
                    grasp_head(rig, w)
                if name == "walk":
                    badges_hang(rig, .33 * sin(2 * pi * t / duration))
                elif name == "sweep":
                    badges_hang(rig, 0, -.25 * sin(2 * pi * (t / 2. - .17)) * sin(pi * t / 2.))
                elif name == "lean":
                    held = min(t, LEAN_HOLD)
                    bend(rig, .9 * (.85 * smoothstep(held / .55) + .15 * smoothstep((held - .55) / 1.95)))
                    badges_hang(rig, .32 * sin(11 * min(t, LEAN_HOLD)) * (1 - smoothstep(t / 1.1)))
                elif name == "snatch":
                    lunge = smoothstep(t / .2) * (1 - smoothstep((t - .2) / .44))
                    badges_hang(rig, -.4 * lunge)
                else:
                    badges_hang(rig)
                opening = .49 * min(smoothstep(t / .133), 1 - smoothstep((t - .14) / .06)) if name == "snatch" else 0.
                blades(rig, blade_axis, opening)
            bpy.context.view_layer.update()
            if name == "lean" and frame == round(LEAN_HOLD * FPS):
                lean_hold = capture(rig)
            if name == "lean" and t > LEAN_HOLD:
                restore(rig, lean_hold)   # the end hold is exactly one pose
            for bone in rig.pose.bones:
                if bone.name == "Root":
                    continue
                bone.keyframe_insert("rotation_quaternion", frame=frame, group=bone.name)
                if bone.name == "Hips":
                    bone.keyframe_insert("location", frame=frame, group=bone.name)
        slot = rig.animation_data.action_slot
        rig.animation_data.action = None
        track = rig.animation_data.nla_tracks.new()
        track.name = name
        strip = track.strips.new(name, 0, action)
        strip.action_slot = slot
        print(f"clip {name}: {duration:.3f} s, {stop + 1} keys")
    rig.animation_data.use_nla = True
    scene.frame_set(0)
    reset(rig)


def strip_jpeg_metadata(path):
    """Godot 4.7 refuses Blender's JPEG because of its colour profile (APP2), so keep only the picture:
    drop APP1, APP2 and comment segments. The JSON's byteLength changes; the binary chunk keeps its layout."""
    import json
    from struct import pack, unpack_from
    data = bytearray(path.read_bytes())
    json_length = unpack_from("<I", data, 12)[0]
    package = json.loads(bytes(data[20:20 + json_length]))
    binary = data[28 + json_length:]
    for image in package["images"]:
        view = package["bufferViews"][image["bufferView"]]
        start = view.get("byteOffset", 0)
        jpeg = bytes(binary[start:start + view["byteLength"]])
        kept, at = bytearray(jpeg[:2]), 2
        while jpeg[at + 1] != 0xDA:
            length = unpack_from(">H", jpeg, at + 2)[0]
            if jpeg[at + 1] not in (0xE1, 0xE2, 0xFE):
                kept += jpeg[at:at + 2 + length]
            at += 2 + length
        kept += jpeg[at:]
        binary[start:start + view["byteLength"]] = kept + bytes(view["byteLength"] - len(kept))
        view["byteLength"] = len(kept)
    text = json.dumps(package, separators=(",", ":")).encode()
    text += b" " * (-len(text) % 4)
    body = pack("<II", len(text), 0x4E4F534A) + text + pack("<II", len(binary), 0x004E4942) + binary
    path.write_bytes(pack("<III", 0x46546C67, 2, 12 + len(body)) + body)


